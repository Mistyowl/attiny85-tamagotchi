export const SPRITE_DEAD = 6;
export const SPRITE_WING_L = 7;
export const SPRITE_WING_R = 8;

export function getSpriteFrame(stageId: number, frame: number): readonly number[] {
  const set = SPRITES[stageId] ?? SPRITES[0];
  return set.frames[frame & 1];
}

export function spritePixel(data: readonly number[], x: number, y: number): boolean {
  if (x < 0 || y < 0 || x >= SPRITE_W || y >= SPRITE_H) return false;
  const i = y * SPRITE_W + x;
  const byte = data[i >> 3];
  const bit = 0x80 >> (i & 7);
  return (byte & bit) !== 0;
}

/** Approximate Flash bytes if stored in PROGMEM. */
export function estimateSpriteFlashBytes(): number {
  return SPRITES.reduce((n, s) => n + s.frames.length * SPRITE_BYTES, 0);
}
