/**
 * 1-bit sprites, 32×32, row-major, MSB = leftmost pixel.
 * Same byte layout intended for AVR PROGMEM.
 *
 * Source art is LCD-export style (ink = 0, bg = 1) — inverted on load
 * so runtime convention stays: bit 1 = draw pixel.
 */

export const SPRITE_W = 32;
export const SPRITE_H = 32;
export const SPRITE_BYTES = (SPRITE_W * SPRITE_H) / 8; // 128

export interface SpriteSet {
  frames: readonly (readonly number[])[];
}

/** Invert LCD Assistant / image2cpp export (0 = ink) → draw-on-1. */
function ink0(data: readonly number[]): number[] {
  return data.map((b) => b ^ 0xff);
}

