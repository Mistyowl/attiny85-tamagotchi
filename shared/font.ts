/** Unique glyphs in FONT_GLYPH × 5 bytes. */
export function estimateFontFlashBytes(): number {
  return Object.keys(FONT_GLYPH).length * 5;
}

/** 5×7 glyph + 1px gap. */
export function textWidthPx(text: string): number {
  return text.length * 6;
}

export function centerTextX(text: string, screenW = 128): number {
  return Math.max(0, Math.floor((screenW - textWidthPx(text)) / 2));
}
